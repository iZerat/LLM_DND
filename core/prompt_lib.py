def scan_triggers(user_input: str) -> list[PromptFragment]:
    matched: list[PromptFragment] = []
    for entry in _TRIGGERS:
        for kw in entry["keywords"]:
            if kw in user_input:
                matched.append((kw, entry["prompt"]))
                break
    return matched


def build_prompt_suffix(user_input: str) -> str:
    fragments = scan_triggers(user_input)
    if not fragments:
        return ""
    parts = []
    for kw, prompt in fragments:
        parts.append(prompt)
    return "\n\n" + "\n".join(parts)
